from __future__ import annotations

from agent_content.models import WorkEvent
from agent_content.utils import clip


class PostGenerator:
    def generate(self, event: WorkEvent) -> str:
        return (
            "Сегодня я снова поймал мысль: почти у любой работы уже есть свой контент.\n\n"
            f"Главный сюжет дня: {event.title.lower()}.\n"
            f"{clip(event.summary, 420)}\n\n"
            "Для меня это может выглядеть как обычный рабочий диалог: вопросы, уточнения, решения, сомнения и короткие повороты по дороге. "
            "Для зрителя это интереснее сформулировать иначе: был хаос, появилась структура, стало понятнее, что делать дальше.\n\n"
            "Я хочу, чтобы AI-агент не просто писал текст по запросу, а внимательно смотрел на реальную работу и помогал доставать из нее живые истории.\n\n"
            "Не придумывать фальшивый контент. Находить настоящий."
        )
