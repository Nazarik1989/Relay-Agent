from __future__ import annotations

from agent_content.config.tone_profiles import TONE_PROFILES
from agent_content.models import WorkEvent
from agent_content.utils import clip


class StoryGenerator:
    def generate(self, event: WorkEvent, count: int = 7) -> list[dict[str, str]]:
        profile = TONE_PROFILES[event.tone]
        seeds = [
            ("Обычный рабочий хаос", "Показать экран с рабочим чатом или заметкой дня."),
            ("Для меня это диалог, а для зрителя история", "Скрин рабочего вопроса с крупной человеческой подписью."),
            ("Главный поворот дня", "Один крупный тезис поверх спокойного рабочего кадра."),
            ("Как это связано с обычной жизнью", "Мини-схема: рутина -> агент -> ясность."),
            ("Что было сложно", "Короткий screen recording момента, где видно поиск решения."),
            ("Что понял сегодня", "Текстовая сторис с одной мыслью без технических деталей."),
            ("Что бы я показал дальше", "Тизер следующего шага или вопрос аудитории."),
            ("До/после", "Две половины экрана: было шумно, стало понятнее."),
            ("AI как внимательный помощник", "Показать, как агент превращает факты в смысл."),
            ("Вопрос аудитории", "Опрос или стикер с простым выбором."),
        ]
        stories = []
        for index, (angle, visual) in enumerate(seeds[:count], start=1):
            stories.append(
                {
                    "title": f"Сторис {index}: {angle}",
                    "text": self._text_for(angle, event),
                    "visual": visual,
                    "style": profile["name"],
                    "goal": self._goal_for(index),
                }
            )
        return stories

    def _text_for(self, angle: str, event: WorkEvent) -> str:
        base = clip(event.summary, 150)
        return {
            "Обычный рабочий хаос": f"Сегодня в работе был момент, который выглядит как техническая рутина, но на самом деле это история: {base}",
            "Для меня это диалог, а для зрителя история": "Я учу агента замечать не файлы и команды, а смысл: что изменилось, зачем это важно и кому от этого станет проще.",
            "Главный поворот дня": f"Главный сюжет: {event.title.lower()}. Это уже не отчет о работе, а материал для живого рассказа.",
            "Как это связано с обычной жизнью": "Если AI может разбирать рабочий хаос разработчика, он сможет помогать и с обычной рутиной: задачами, заметками, решениями.",
            "Что было сложно": "Самое сложное не сгенерировать текст. Сложнее выбрать, что вообще стоит рассказывать людям.",
            "Что понял сегодня": "Контент часто уже есть внутри работы. Его не надо выдумывать, его надо внимательно заметить.",
            "Что бы я показал дальше": "Следующий шаг: чтобы агент сам собирал такие моменты каждый день и складывал их в очередь на публикацию.",
            "До/после": "До: набор рабочих реплик и решений. После: понятная история, которую можно показать человеку без технического бэкграунда.",
            "AI как внимательный помощник": "Мне нравится мысль, что AI может быть не автором вместо человека, а внимательным редактором рядом.",
            "Вопрос аудитории": "А вы бы доверили AI собирать идеи для контента из вашей рабочей переписки?",
        }.get(angle, base)

    def _goal_for(self, index: int) -> str:
        goals = [
            "зацепить любопытством",
            "объяснить ценность без жаргона",
            "показать сюжет дня",
            "связать разработку с жизнью",
            "дать честное закулисье",
            "сформулировать инсайт",
            "пригласить следить за развитием",
        ]
        return goals[(index - 1) % len(goals)]
